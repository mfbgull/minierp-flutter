const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const run = path.join(root, 'accounting-audit/evidence/backend-run-Lbw3la');
const data = JSON.parse(fs.readFileSync(path.join(run, 'results.json')));
assert.equal(data.completed, true);
assert.equal(data.error, undefined);
const scenario = id => { const value=data.scenarios.find(x=>x.id===id); assert(value); return value; };
const payroll=scenario('BACKEND-SALARY-ADVANCE-RECOGNITION');
assert.deepEqual(payroll.actual.august, {salaryExpense:1000,advanceAsset:200,bank:8800});
assert.deepEqual(payroll.actual.september, {salaryExpense:1800,advanceAsset:200,bank:8000});
assert.equal(payroll.actual.profitLoss.data.totalExpenses,1800);
assert.equal(payroll.actual.balanceSheet.data.assets.other,200);
assert.equal(payroll.actual.balanceSheet.data.totals.balanced,true);
const loan=scenario('BACKEND-LOAN-PREDISBURSEMENT');
assert.deepEqual(loan.actual,{status:201,loanReceivableBeforeDisbursement:-200});
const production=scenario('BACKEND-PRODUCTION-ROUNDING');
assert.equal(production.actual.status,201);
assert.deepEqual(production.actual.outputRows.map(x=>x.allocated_cost),[0.01,0.01,0.01,-0.01]);
assert.deepEqual(production.actual.productionAfter,{inventory:0.03,clearing:-0.01});
const settlement=scenario('BACKEND-CLOSED-SOURCE-SETTLEMENT');
assert.equal(settlement.actual.expenseStatus,409);assert.equal(settlement.actual.billStatus,409);
assert.deepEqual(settlement.actual.beforeSettlement,settlement.actual.afterSettlement);
const Database=require(path.join(root,'server/node_modules/better-sqlite3'));
const db=new Database(path.join(run,'erp.db'),{readonly:true,fileMustExist:true});
assert.equal(db.pragma('integrity_check',{simple:true}),'ok');
assert.deepEqual(db.pragma('foreign_key_check'),[]);
const negative=db.prepare('SELECT item_id,unit_cost,quantity_remaining FROM stock_batches WHERE unit_cost<0').all();
assert.equal(negative.length,1);assert.equal(negative[0].unit_cost,-0.01);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM journal_entry_balances WHERE balance_cents!=0').get().n,0);
const assertions={verifiedAt:new Date().toISOString(),run,checks:['F020 exact wages/asset and report misstatement','F021 pre-disbursement negative loan receivable','F022 negative batch costs and inventory/clearing mismatch','F023 both source-period settlement rejections, balances unchanged','SQLite integrity/FK checks clean','All journal groups balance despite economic defects'],negativeCostBatches:negative};
fs.writeFileSync(path.join(root,'accounting-audit/evidence/backend-verification.json'),JSON.stringify(assertions,null,2));
db.close();console.log(JSON.stringify(assertions,null,2));
